import { cp, lstat, mkdir, mkdtemp, readFile, readdir, rename, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const marker = '.framework-engine-static-build';
const allowedExtensions = new Set(['.html', '.css', '.js']);

function parseOutput(argv) {
  const flag = argv.indexOf('--out-dir');
  if (flag === -1) return path.join(projectRoot, 'dist');
  if (flag !== 0 || !argv[1] || argv.length !== 2) {
    throw new Error('Usage: node scripts/build-static.js [--out-dir <directory>]');
  }
  return path.resolve(argv[1]);
}

async function copyAppTree(source, destination) {
  const entries = await readdir(source, { withFileTypes: true });
  await mkdir(destination, { recursive: true });
  for (const entry of entries) {
    const sourcePath = path.join(source, entry.name);
    const destinationPath = path.join(destination, entry.name);
    if (entry.isSymbolicLink()) throw new Error(`Static build does not follow symlinks: ${sourcePath}`);
    if (entry.isDirectory()) {
      await copyAppTree(sourcePath, destinationPath);
    } else if (entry.isFile() && allowedExtensions.has(path.extname(entry.name))) {
      await cp(sourcePath, destinationPath);
    }
  }
}

async function build(output) {
  await mkdir(path.dirname(output), { recursive: true });
  const staging = await mkdtemp(`${output}.staging-`);
  try {
    await mkdir(staging, { recursive: true });
    await Promise.all(['examples', 'src'].map(name =>
      copyAppTree(path.join(projectRoot, name), path.join(staging, name))));
    await writeFile(path.join(staging, 'index.html'), '<!doctype html>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1">\n<title>Framework Engine</title>\n<meta http-equiv="refresh" content="0; url=./examples/">\n<p><a href="./examples/">Open Framework Engine</a></p>\n');
    await writeFile(path.join(staging, marker), 'Generated by npm run build:static.\n');

    try {
      const info = await lstat(output);
      if (!info.isDirectory() || info.isSymbolicLink()) {
        throw new Error(`Refusing to replace non-directory output: ${output}`);
      }
      try {
        await readFile(path.join(output, marker), 'utf8');
      } catch {
        throw new Error(`Refusing to replace unowned output directory: ${output}`);
      }
      await rm(output, { recursive: true });
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
    await rename(staging, output);
  } catch (error) {
    await rm(staging, { recursive: true, force: true });
    throw error;
  }
}

const output = parseOutput(process.argv.slice(2));
await build(output);
console.log(`Static site written to ${path.relative(projectRoot, output) || '.'}`);
